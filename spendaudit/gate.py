"""Data gate (spec §2): profile a loaded source, decide go/no-go, write DATA.md."""

from datetime import date
from pathlib import Path
from typing import Any

import polars as pl

from spendaudit import ROOT

MIN_ROWS = 100_000
MIN_DAYS = 730 - 31  # "≥2 years": 24 calendar months of data


def _month(yyyymm: object) -> str:
    s = str(yyyymm)
    return f"{s[:4]}-{s[4:6]}"


def profile(df: pl.DataFrame) -> dict[str, Any]:
    valid = df.filter(pl.col("amount").is_not_null() & pl.col("date").is_not_null())
    first, last = valid["date"].min(), valid["date"].max()
    assert isinstance(first, date) and isinstance(last, date)
    p: dict[str, Any] = {
        "rows_raw": df.height,
        "rows": valid.height,
        "rows_dropped": df.height - valid.height,
        "first_date": first.isoformat(),
        "last_date": last.isoformat(),
        "days": (last - first).days,
        "months": valid.select(pl.col("txn_id").str.slice(1, 6).n_unique()).item(),
        # Statement months (from the files); some transactions are dated months before posting.
        "first_month": _month(valid["txn_id"].str.slice(1, 6).min()),
        "last_month": _month(valid["txn_id"].str.slice(1, 6).max()),
        "dollars": round(float(valid["amount"].sum()), 2),
        "dollars_positive": round(float(valid.filter(pl.col("amount") > 0)["amount"].sum()), 2),
        "refunds": valid.filter(pl.col("amount") < 0).height,
        "agencies": valid["agency"].n_unique(),
        "cards": valid["card_key"].n_unique(),
        "mcc_categories": valid["mcc"].n_unique(),
        "null_rates": {c: round(df[c].null_count() / max(df.height, 1), 5) for c in df.columns},
    }
    checks = {
        f"≥{MIN_ROWS:,} transactions": p["rows"] >= MIN_ROWS,
        "≥2 years of data": p["days"] >= MIN_DAYS,
        "amount, date, merchant, agency present": all(
            p["null_rates"][c] < 0.01 for c in ("amount", "date", "merchant_raw", "agency")
        ),
        "per-card key present": p["cards"] > 1,
    }
    p["checks"] = checks
    p["go"] = all(checks.values())
    return p


def write_data_md(p: dict[str, Any], source: str, path: Path = ROOT / "DATA.md") -> None:
    lines = [
        "# DATA.md — data gate",
        "",
        "_Generated by `python -m spendaudit build`. Do not edit by hand._",
        "",
        f"**Source:** {source}",
        "",
        f"**Decision: {'GO' if p['go'] else 'NO-GO'}**",
        "",
        "| Check | Result |",
        "|---|---|",
        *[f"| {k} | {'pass' if v else 'FAIL'} |" for k, v in p["checks"].items()],
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Transactions (usable) | {p['rows']:,} |",
        f"| Rows dropped (unparseable amount/date) | {p['rows_dropped']:,} |",
        f"| Statement months | {p['first_month']} to {p['last_month']} ({p['months']} months) |",
        f"| Transaction dates | {p['first_date']} to {p['last_date']} (late postings included) |",
        f"| Net dollars | ${p['dollars']:,.2f} |",
        f"| Gross purchases (positive amounts) | ${p['dollars_positive']:,.2f} |",
        f"| Refunds / credits | {p['refunds']:,} |",
        f"| Agencies | {p['agencies']:,} |",
        f"| Cards (agency + surname + initial) | {p['cards']:,} |",
        f"| Merchant-category descriptions | {p['mcc_categories']:,} |",
        "",
        "Null rates by field:",
        "",
        "| Field | Null rate |",
        "|---|---|",
        *[f"| {k} | {v:.3%} |" for k, v in p["null_rates"].items()],
        "",
        "Notes: the files carry a merchant-category *description* (not the 4-digit code), and no",
        "card number, so a card is identified by agency + cardholder surname + first initial,",
        "hashed with a private salt. Names are never stored after loading.",
    ]
    path.write_text("\n".join(lines) + "\n")
